def update_po_file(filepath, lang_dict):
    if not os.path.exists(filepath):
        return
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    count = 0
    for msgid, msgstr in lang_dict.items():
        # Match msgid "..." followed by msgstr ""
        pattern = re.compile(r'(msgid\s+"' + re.escape(msgid) + r'"\s*\nmsgstr\s+)""', re.MULTILINE)
        if pattern.search(content):
            safe_msgstr = msgstr.replace('\\', '\\\\').replace('"', '\\"')
            content = pattern.sub(r'\1"' + safe_msgstr + '"', content)
            count += 1
        elif ('msgid "' + msgid + '"') not in content:
            safe_msgid = msgid.replace('\\', '\\\\').replace('"', '\\"')
            safe_msgstr = msgstr.replace('\\', '\\\\').replace('"', '\\"')
            content += f'\n\nmsgid "{safe_msgid}"\nmsgstr "{safe_msgstr}"\n'
            count += 1

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Updated {filepath} with {count} translations.")

for lang, d in translations.items():
    po_path = f"/www/wwwroot/statsfut.com/locale/{lang}/LC_MESSAGES/django.po"
    update_po_file(po_path, d)
